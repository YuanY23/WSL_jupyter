"""
一维稳态导热 —— 无限大平板导热（第一类边界条件）
============================================================
数值方法：有限差分法 (Finite Difference Method, FDM)

物理模型
--------
一块厚度为 L 的无限大平板，导热系数 k 为常数，板内无内热源。
左右两侧分别维持恒定温度 T_h（高温侧）和 T_c（低温侧）。

    ┌──────────────────────┐
    │                      │
  T_h        k = const       T_c
    │                      │
    └──────────────────────┘
    x=0                    x=L

控制方程（一维稳态、无内热源）
------------------------------
    d²T/dx² = 0       (0 < x < L)

边界条件（第一类 / Dirichlet）
------------------------------
    T(0) = T_h
    T(L) = T_c

解析解
------
    T(x) = T_h + (T_c - T_h) · x / L
    q = k · (T_h - T_c) / L          (热流密度, W/m²)
    R = L / k                         (单位面积热阻, K·m²/W)

FDM 离散过程
------------
将 [0, L] 均匀划分为 N-1 段，共 N 个节点，节点间距 Δx = L/(N-1)。

对每个内部节点 i (i = 1, 2, ..., N-2)，用中心差分近似二阶导数：

    (T_{i-1} - 2·T_i + T_{i+1}) / Δx² = 0

整理得：
    T_{i-1} - 2·T_i + T_{i+1} = 0

加上边界条件，组装为线性方程组 [A]{T} = {b}：

    ┌ 1    0    0   ...         ┐ ┌ T_0   ┐   ┌ T_h ┐
    │ 1   -2    1   0   ...     │ │ T_1   │   │  0  │
    │ 0    1   -2   1   ...     │ │ T_2   │ = │  0  │
    │ ...            ...        │ │  ...  │   │ ... │
    └         ...  0    0    1  ┘ └ T_{N-1}┘   └ T_c ┘

系数矩阵为三对角矩阵，可高效求解。
"""

import numpy as np


def solve_flat_plate(params: dict) -> dict:
    """
    无限大平板稳态导热 · 有限差分法 (FDM) 求解

    Parameters (通过 params 字典传入)
    ----------
    thickness            : 平板厚度 L (m), 默认 0.1
    thermal_conductivity : 导热系数 k (W/(m·K)), 默认 400
    temp_left            : 左侧温度 T_h (°C), 默认 100
    temp_right           : 右侧温度 T_c (°C), 默认 20
    n_nodes              : 网格节点数 (可选), 默认 50

    Returns
    -------
    dict : 包含 indicators 和 chart_data
    """
    # ---------- 读取参数 ----------
    L   = float(params.get('thickness', 0.1))
    k   = float(params.get('thermal_conductivity', 400))
    T_h = float(params.get('temp_left', 100))
    T_c = float(params.get('temp_right', 20))
    n   = int(params.get('n_nodes', 50))

    dx = L / (n - 1)
    x  = np.linspace(0, L, n)

    # ========================================================
    # 第一步：组装系数矩阵（三对角矩阵）
    # ========================================================
    A = np.zeros((n, n))
    b = np.zeros(n)

    # 边界节点 —— 直接赋值
    A[0, 0]   = 1.0
    b[0]      = T_h

    A[-1, -1] = 1.0
    b[-1]     = T_c

    # 内部节点 —— 中心差分: T_{i-1} - 2T_i + T_{i+1} = 0
    for i in range(1, n - 1):
        A[i, i - 1] =  1.0
        A[i, i]     = -2.0
        A[i, i + 1] =  1.0
        b[i]        =  0.0

    # ========================================================
    # 第二步：求解线性方程组
    # ========================================================
    T_numerical = np.linalg.solve(A, b)

    # ========================================================
    # 第三步：计算解析解（用于验证）
    # ========================================================
    T_analytical = T_h + (T_c - T_h) * x / L

    # ========================================================
    # 第四步：计算工程物理量
    # ========================================================
    q = k * (T_h - T_c) / L       # 热流密度 (W/m²)
    R = L / k                      # 单位面积热阻 (K·m²/W)
    max_error = float(np.max(np.abs(T_numerical - T_analytical)))

    # ---------- 返回标准格式 ----------
    return {
        "indicators": {
            "热流密度 q (W/m²)": round(float(q), 4),
            "单位面积热阻 R (K·m²/W)": round(float(R), 6),
            "数值方法": "有限差分法 (FDM)",
            "网格节点数": n,
            "数值解与解析解最大误差 (°C)": f"{max_error:.2e}",
        },
        "chart_data": {
            "x": x.tolist(),
            "y": T_numerical.tolist(),
            "x_label": "位置 x (m)",
            "y_label": "温度 T (°C)",
            "title": "无限大平板稳态导热温度分布 (FDM)",
        },
    }
